// === 创意跳跃知识 ===

export interface LeapKnowledge {
  /** 跳跃类型key */
  type: string;
  /** 中文名 */
  name: string;
  /** 什么时候该用（触发场景） */
  triggers: string[];
  /** 什么时候不该用 */
  avoidWhen: string[];
  /** 生成方向（具体往哪个方向跳） */
  directions: string[];
  /** 网文实例（不是抽象描述，是具体写法示例） */
  examples: string[];
  /** 约束条件（不能违反什么） */
  constraints: string[];
  /** 评分标准 */
  scoring: {
    novelty: string;
    relevance: string;
    impact: string;
  };
  /** 低水平 vs 高水平对比示例 */
  levelComparison?: {
    low: string;
    high: string;
    difference: string;
  };
  /** 绝对禁用场景：什么时候用了反而会破坏阅读体验 */
  neverUseWhen?: string[];
}

