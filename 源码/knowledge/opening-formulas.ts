/** 开篇公式类型 */
export type OpeningFormulaType =
  | 'dead_end'           // 绝境冲突型
  | 'identity_reversal'  // 身份反差型
  | 'behavior_reversal'  // 行为反差型
  | 'result_first'       // 结果前置型
  | 'rule_subversion'    // 规则颠覆型
  | 'info_potential';    // 信息势能型

/** 顶流网文案例分析 */
export interface OpeningCaseStudy {
  /** 小说名 */
  novel: string;
  /** 章节/场景 */
  chapter: string;
  /** 简述这个开篇怎么用的 */
  excerpt: string;
  /** 为什么这个例子好 */
  analysis: string;
}

/** 开篇公式 */
export interface OpeningFormula {
  /** 类型 */
  type: OpeningFormulaType;
  /** 中文名 */
  name: string;
  /** 一句话描述 */
  description: string;
  /** 适用场景 */
  bestFor: string[];
  /** 不适用场景 */
  worstFor: string[];
  /** 执行方法（分步指南） */
  howTo: {
    /** 第一步：怎么开头 */
    step1: string;
    /** 第二步：怎么展开 */
    step2: string;
    /** 第三步：怎么收尾 */
    step3: string;
  };
  /** 好的示例（来自真实网文） */
  goodExample: string;
  /** 坏的示例（常见错误写法） */
  badExample: string;
  /** 为什么这个公式有效 */
  whyItWorks: string;
  /** 间距建议（同一公式最小间隔章数） */
  minInterval: number;
  /** 顶流网文案例（v9.0新增） */
  caseStudies?: OpeningCaseStudy[];
}

