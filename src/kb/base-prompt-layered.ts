- 读者只有3秒决定要不要看下去。第一句≤20字，直接写正在发生的动作/冲突/结果。
- 前300字完成三件事：冲突爆发→主角身体在场→异常信号出现。
- 前300字禁止：写景、交代背景、介绍人物、回忆前世、说明世界观。
