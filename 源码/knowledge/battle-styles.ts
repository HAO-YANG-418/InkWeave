/** 战斗风格类型 */
export type BattleStyleType =
  | 'intelligence'    // 诡秘博弈型：智斗+情报战，信息不对称是核心
  | 'overwhelming'    // 碾压爽快型：实力碾压，一招制敌
  | 'comeback'        // 绝境翻盘型：被压到极限后翻盘
  | 'artistic'        // 意境写意型：战斗如诗，重在气势意境
  | 'team_strategy';  // 策略团战型：多人配合，战术协同

/** 战斗阶段 */
export interface BattlePhase {
  /** 阶段名称 */
  name: string;
  /** 位置（战斗全程百分比，0-100） */
  position: number;
  /** 描述 */
  description: string;
  /** 怎么写 */
  howTo: string;
}

/** 顶流网文战斗案例 */
export interface BattleCaseStudy {
  novel: string;
  scene: string;
  excerpt: string;
  analysis: string;
}

/** 战斗风格 */
export interface BattleStyle {
  /** 类型 */
  type: BattleStyleType;
  /** 名称 */
  name: string;
  /** 一句话描述 */
  description: string;
  /** 适用场景 */
  bestFor: string[];
  /** 不适用场景 */
  worstFor: string[];
  /** 战斗阶段 */
  phases: BattlePhase[];
  /** 好的示例（来自真实网文） */
  goodExample: string;
  /** 坏的示例 */
  badExample: string;
  /** 为什么有效 */
  whyItWorks: string;
  /** 节奏特点 */
  rhythm: string;
  /** 关键词（用于匹配场景） */
  keywords: string[];
  /** 顶流网文案例（v9.0新增） */
  caseStudies?: BattleCaseStudy[];
}

