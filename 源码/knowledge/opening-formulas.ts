/** 根据章节意图推荐开篇公式 */
export function recommendOpeningFormula(
  chapterIntent: string,
  previousOpenings: OpeningFormulaType[],
  genre?: string,
): OpeningFormula | null {
  // 检查最近使用的公式，排除冷却中的
  const recentSet = new Set(previousOpenings.slice(-3));
  const available = OPENING_FORMULAS.filter(f => !recentSet.has(f.type));

  // 根据意图打分
  const scored = available.map(f => {
    let score = 0;
    const intent = chapterIntent.toLowerCase();

    if (f.bestFor.some(s => intent.includes(s) || s.includes(intent))) score += 3;
    if (genre && f.bestFor.some(s => s.includes(genre))) score += 2;
    if (f.worstFor.some(s => intent.includes(s))) score -= 5;

    return { formula: f, score };
  });

  scored.sort((a, b) => b.score - a.score);

  return scored[0]?.formula ?? null;
}

/** 生成开篇指导 Prompt */
export function generateOpeningPrompt(formula: OpeningFormula): string {
  const cases = formula.caseStudies && formula.caseStudies.length > 0
    ? `\n\n顶流网文案例：\n${formula.caseStudies.map((c, i) =>
        `${i + 1}. ${c.novel} - ${c.chapter}\n   场景：${c.excerpt}\n   分析：${c.analysis}`
      ).join('\n\n')}`
    : '';

  return `【开篇指导 - ${formula.name}】
${formula.description}

写法：
1. ${formula.howTo.step1}
2. ${formula.howTo.step2}
3. ${formula.howTo.step3}

参考示例：
${formula.goodExample}

为什么有效：${formula.whyItWorks}${cases}`;
}