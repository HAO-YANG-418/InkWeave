/** 根据场景推荐战斗风格 */
export function recommendBattleStyle(
  scene: string,
  genre?: string,
  previousStyles?: BattleStyleType[],
): BattleStyle | null {
  const recentSet = new Set(previousStyles?.slice(-1) || []);
  const available = BATTLE_STYLES.filter(s => !recentSet.has(s.type));

  const scored = available.map(s => {
    let score = 0;
    const sceneLower = scene.toLowerCase();

    // 关键词匹配
    for (const kw of s.keywords) {
      if (sceneLower.includes(kw)) score += 2;
    }
    // 场景匹配
    if (s.bestFor.some(bf => sceneLower.includes(bf) || bf.includes(sceneLower))) score += 3;
    if (genre && s.bestFor.some(bf => bf.includes(genre))) score += 2;
    if (s.worstFor.some(wf => sceneLower.includes(wf))) score -= 5;

    return { style: s, score };
  });

  scored.sort((a, b) => b.score - a.score);

  return scored[0]?.style ?? null;
}

/** 生成战斗风格指导 Prompt */
export function generateBattleStylePrompt(style: BattleStyle): string {
  const phaseDesc = style.phases.map(p => {
    return `阶段${Math.round(p.position)}%：${p.name}
    ${p.description}
    → ${p.howTo}`;
  }).join('\n\n');

  const cases = style.caseStudies && style.caseStudies.length > 0
    ? `\n\n顶流网文案例：\n${style.caseStudies.map((c, i) =>
        `${i + 1}. ${c.novel} - ${c.scene}\n   场景：${c.excerpt}\n   分析：${c.analysis}`
      ).join('\n\n')}`
    : '';

  return `【战斗风格指导 - ${style.name}】
${style.description}

节奏：${style.rhythm}

战斗阶段：
${phaseDesc}

参考示例：
${style.goodExample}

为什么有效：${style.whyItWorks}

写作要求：
- 严格遵循${style.phases.length}个阶段的节奏
- 不要跳过阶段——每个阶段都有必要的叙事功能
- ${style.type === 'intelligence' ? '用主角的观察和推理来推动战斗，不要写"主角灵光一闪"' : ''}
- ${style.type === 'overwhelming' ? '用旁观者的反应和环境的破坏来展示实力，不要直接说"主角很强"' : ''}
- ${style.type === 'comeback' ? '翻盘必须有"为什么能翻盘"的解释，不能是"突然爆发"' : ''}
- ${style.type === 'artistic' ? '少写招式，多写气势——用环境变化强化氛围，但关键动作与结果必须写清，不藏逻辑' : ''}
- ${style.type === 'team_strategy' ? '每个角色都要有不可替代的贡献，不能是"大家一起打"' : ''}${cases}`;
}