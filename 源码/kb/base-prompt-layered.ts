/** 场景枚举 */
export type PromptLayer = 'core' | 'extended' | 'reference' | 'full';

/** 根据能力类型获取需要的层面 */
export function getLayersForCapability(capability: string): PromptLayer[] {
  switch (capability) {
    case 'continue':
      return ['core']; // 续写只装核心层
    case 'rewrite':
    case 'polish':
    case 'compress':
      return ['core', 'extended']; // 改写/润色装核心+扩展
    case 'expand':
      return ['core', 'extended'];
    case 'review':
    case 'consistency':
      return ['core', 'extended', 'reference']; // 审稿装全部
    case 'outline':
      return ['core', 'extended', 'reference'];
    case 'dialog':
      return ['core']; // 对话只装核心
    default:
      return ['core', 'extended', 'reference'];
  }
}

/** 根据质量分数决定是否追加扩展层 */
export function shouldLoadExtended(qualityScore: number): boolean {
  return qualityScore < 0.65; // 质量低于阈值时追加扩展规则
}

/** 组装分层 prompt */
export function buildLayeredPrompt(layers: PromptLayer[]): string {
  const parts: string[] = [];

  if (layers.includes('core')) {
    parts.push(CORE_RULES);
  }
  if (layers.includes('extended')) {
    parts.push('\n' + EXTENDED_RULES);
  }
  if (layers.includes('reference')) {
    parts.push('\n' + REFERENCE_RULES);
  }
  if (layers.includes('full')) {
    parts.push(CORE_RULES + '\n' + EXTENDED_RULES + '\n' + REFERENCE_RULES);
  }

  return parts.join('\n');
}

/** 获取核心层 token 数（估算） */
export function estimateCoreTokens(): number {
  return Math.ceil(CORE_RULES.length / 2.5);
}

/** 获取扩展层 token 数（估算） */
export function estimateExtendedTokens(): number {
  return Math.ceil(EXTENDED_RULES.length / 2.5);
}

/** 获取参考层 token 数（估算） */
export function estimateReferenceTokens(): number {
  return Math.ceil(REFERENCE_RULES.length / 2.5);
}

/** 获取完整 prompt token 数（估算） */
export function estimateFullTokens(): number {
  return Math.ceil((CORE_RULES.length + EXTENDED_RULES.length + REFERENCE_RULES.length) / 2.5);
}

