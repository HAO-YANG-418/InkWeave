// === 工具函数 ===

/** 按类型获取跳跃知识 */
export function getLeapKnowledgeByType(type: string): LeapKnowledge | undefined {
  return LEAP_KNOWLEDGE.find(l => l.type === type);
}

/** 根据场景匹配适合的跳跃类型 */
export function matchLeapsByScenario(scenario: string): LeapKnowledge[] {
  return LEAP_KNOWLEDGE.filter(l =>
    l.triggers.some(t => scenario.includes(t) || t.includes(scenario))
  );
}

/** 生成创意跳跃prompt（供LLM使用） */
export function generateLeapPrompt(): string {
  const leaps = LEAP_KNOWLEDGE.map(l => {
    return `【${l.name}】
触发：${l.triggers.join('；')}
方向：${l.directions.join('；')}
约束：${l.constraints.join('；')}
示例：${l.examples.join('；')}`;
  }).join('\n\n');

  return `你是网文创意顾问。根据当前章节内容，生成有创意且与故事相关的写作灵感。

${leaps}

请根据章节内容选择1-3种最合适的跳跃类型，生成具体的创意建议。每个建议必须与当前剧情/角色/世界观相关。`;
}
